#!/usr/bin/env node

/**
 * Simple approach: Remove fetcher imports and functions, keep all types
 */

import { readFileSync, writeFileSync } from 'fs';

const input = './generated/openadr3Components.ts';
const output = '../package/src/generated/openadr3Components.ts';

console.log('📄 Cleaning API component types...');

let content = readFileSync(input, 'utf-8');

// Replace fetcher imports with clean imports
content = content.replace(/import type \* as Fetcher from "\.\/openadr3Fetcher";?\n?/g, '');
content = content.replace(/import { openadr3Fetch } from "\.\/openadr3Fetcher";?\n?/g, '');

// Fix remaining imports to use .js extension
content = content.replace(/from "\.\/openadr3Schemas"/g, 'from "./openadr3Schemas.js"');
content = content.replace(/from "\.\/openadr3Responses"/g, 'from "./openadr3Responses.js"');

// Remove all Fetcher.ErrorWrapper references and replace with simpler union types
content = content.replace(/Fetcher\.ErrorWrapper<([^>]+)>/g, '$1');

// Remove all function exports (export const functionName = ...)
content = content.replace(/export const [a-zA-Z0-9_]+ = \([^}]+\{[^}]+\}[^}]+\}[^}]+\}[^;]+;?\n?/gms, '');

// Remove remaining function exports that span multiple lines
const lines = content.split('\n');
const cleanLines = [];
let skipFunction = false;
let braceCount = 0;

for (let i = 0; i < lines.length; i++) {
  const line = lines[i];
  
  // Start skipping if we hit a function export
  if (line.startsWith('export const ') && line.includes('=')) {
    skipFunction = true;
    braceCount = 0;
  }
  
  if (skipFunction) {
    // Count braces to know when function ends
    braceCount += (line.match(/\{/g) || []).length;
    braceCount -= (line.match(/\}/g) || []).length;
    
    // Function ended
    if (braceCount === 0 && line.includes(';')) {
      skipFunction = false;
    }
    continue; // Skip this line
  }
  
  // Keep the line
  cleanLines.push(line);
}

const result = cleanLines.join('\n')
  // Clean up any extra whitespace
  .replace(/\n\n\n+/g, '\n\n')
  // Add header comment
  .replace(/^\/\*\*[^*]*\*\//, `/**
 * Generated by @openapi-codegen
 *
 * @version 1.0.0
 * API Component Types - Parameters and Responses for OpenADR 3.1.0 endpoints
 */`);

writeFileSync(output, result);

const typeCount = (result.match(/export type /g) || []).length;
console.log(`✅ Cleaned ${typeCount} API component types`);
console.log('📁 Generated: package/src/generated/openadr3Components.ts');